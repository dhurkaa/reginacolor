import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {CATALOG_PRODUCTS,CATALOG_VARIANTS} from '../catalog.js';
import {LocalBackend} from '../local-backend.js';
const items=new Map();
globalThis.localStorage={getItem:k=>items.has(k)?items.get(k):null,setItem:(k,v)=>items.set(k,String(v)),removeItem:k=>items.delete(k)};
assert.equal(CATALOG_PRODUCTS.length,54,'numri i produkteve');
assert.equal(CATALOG_VARIANTS.length,199,'numri i varianteve');
assert.equal(new Set(CATALOG_PRODUCTS.map(x=>x.id)).size,54);
assert.equal(new Set(CATALOG_VARIANTS.map(x=>x.id)).size,199);
assert.equal(CATALOG_VARIANTS.filter(v=>v.shade_code?.startsWith('RG')).length,72);
assert.equal(CATALOG_VARIANTS.filter(v=>v.shade_code?.startsWith('MX')).length,24);
assert.deepEqual(CATALOG_PRODUCTS.find(p=>p.name==='Teifgrund').sizes,['1 kg','4 kg','15 kg']);
assert.deepEqual(CATALOG_PRODUCTS.find(p=>p.name==='Reflex Waterproofing (A+B)').sizes,['25 kg + 8 kg']);
const app=new LocalBackend();await app.init();const initial=await app.load();
const client=initial.clients.find(c=>c.name==='Termo Projekt'&&c.location==='Istog');assert.ok(client);
const variant=CATALOG_VARIANTS.find(v=>CATALOG_PRODUCTS.find(p=>p.id===v.product_id)?.name==='Bau Fassade Full A 1.5mm');assert.ok(variant);
await app.switchRole('demo-agent');
const orderId=await app.createOrder(client.id,[{variant_id:variant.id,qty:27}],'Porosi prove');
await assert.rejects(app.registerShipment(orderId,[],false,''),/leje/);
await app.switchRole('demo-warehouse');
await app.setOrderStatus(orderId,'preparing');
let data=await app.load();let line=data.order_items.find(x=>x.order_id===orderId);assert.equal(line.ordered_qty,27);
await assert.rejects(app.registerShipment(orderId,[{order_item_id:line.id,qty:30}],false,''),/tejkalon/);
await app.registerShipment(orderId,[{order_item_id:line.id,qty:25}],true,'Dërguar 25');
data=await app.load();line=data.order_items.find(x=>x.order_id===orderId);const ord=data.orders.find(x=>x.id===orderId);
assert.equal(ord.status,'completed');assert.equal(line.ordered_qty,27);assert.equal(line.fulfilled_qty,25);assert.equal(line.ordered_qty-line.fulfilled_qty,2);
assert.equal(data.shipments.length,1);assert.equal(data.shipment_items[0].quantity,25);
assert.ok(ord.completed_at);
await app.switchRole('demo-admin');await app.reopenOrder(orderId);data=await app.load();assert.equal(data.orders.find(x=>x.id===orderId).status,'partial');
await app.adjustOrderItem(line.id,28);data=await app.load();assert.equal(data.order_items.find(x=>x.id===line.id).ordered_qty,28);
const schema=readFileSync(new URL('../supabase/schema.sql',import.meta.url),'utf8');
assert.match(schema,/enable row level security/i);
// Kontrollet e lejeve duhet të bllokojnë edhe përdoruesit joaktivë (rol NULL).
assert.doesNotMatch(schema,/if public\.(current_role|app_role)\(\)\s*(not in|<>)/i,'kontroll lejesh që lejon NULL');
for(const fn of ['create_order','set_order_status','register_shipment','adjust_order_item','reopen_order','set_product_price','set_item_price','fill_missing_prices'])
  assert.match(schema,new RegExp(`function public\\.${fn}\\([\\s\\S]*?perform public\\.require_role`),fn+' pa require_role');
assert.match(schema,/revoke all on function %s from public, anon/);

// Çmimet: lista, kopjimi në porosi, ndryshimi i listës nuk ndryshon porositë e vjetra, plotësimi i mungesave.
await app.switchRole('demo-agent');
await assert.rejects(app.setProductPrice(variant.product_id,variant.size_label,10),/administratori/);
await app.switchRole('demo-admin');
await app.setProductPrice(variant.product_id,variant.size_label,24.5);
await app.switchRole('demo-agent');
const pricedId=await app.createOrder(client.id,[{variant_id:variant.id,qty:4}],'');
data=await app.load();let pricedLine=data.order_items.find(x=>x.order_id===pricedId);assert.equal(pricedLine.unit_price,24.5);
await app.switchRole('demo-admin');
await app.setProductPrice(variant.product_id,variant.size_label,30);
data=await app.load();assert.equal(data.order_items.find(x=>x.id===pricedLine.id).unit_price,24.5,'çmimi i vjetër mbetet');
await app.setItemPrice(pricedLine.id,22);data=await app.load();assert.equal(data.order_items.find(x=>x.id===pricedLine.id).unit_price,22);
await app.setItemPrice(pricedLine.id,null);assert.equal(await app.fillMissingPrices(pricedId),1);
data=await app.load();assert.equal(data.order_items.find(x=>x.id===pricedLine.id).unit_price,30);
assert.ok(data.order_events.some(ev=>ev.event_type==='price_adjusted'));
console.log('✓ Çmimet: lista, kopjim në porosi, korrigjim, plotësim nga lista, leje vetëm për admin');
console.log('✓ 54 produkte, 199 variante, 72 RG, 24 MX');
